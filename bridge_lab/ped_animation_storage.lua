-- Validates and persists definitions created by the Bridge Lab Ped Animation Editor.
TSSBridgeLabPedAnimationStorage = {}

local Storage = TSSBridgeLabPedAnimationStorage
local resourceName = GetCurrentResourceName()
local animationOutputPath = 'bridge_lab/exported_data/created_ped_animation.lua'
local saveCooldowns = {}
local animationHeader = [[-- Generated by the TSS Bridge Lab Ped Animation Editor.
-- This file is append-only and is not loaded automatically by tss_bridge.
TSSBridgeLabCreatedPedAnimations = TSSBridgeLabCreatedPedAnimations or {}

]]

local function finite(value, limit)
    value = tonumber(value)
    if not value or value ~= value or math.abs(value) > (limit or 10000.0) then return nil end
    return value + 0.0
end

local function safeText(value, maximum, optional)
    if value == nil and optional then return nil end
    if type(value) ~= 'string' then return nil end
    value = value:match('^%s*(.-)%s*$')
    if value == '' then return optional and nil or nil end
    if #value > maximum or value:find('[%c]') or not value:match('^[%w_@%-%./]+$') then return nil end
    return value
end

local function validate(entry)
    if type(entry) ~= 'table' or type(entry.coords) ~= 'table' then return nil, 'Invalid ped payload' end
    local model = safeText(entry.model, 80, false)
    local x, y = finite(entry.coords.x), finite(entry.coords.y)
    local z, w = finite(entry.coords.z, 2000.0), finite(entry.coords.w, 360000.0)
    if not model or not x or not y or not z or not w then return nil, 'Invalid ped model or coordinates' end
    local scenario = safeText(entry.scenario, 96, true)
    local anim
    if entry.anim ~= nil then
        if type(entry.anim) ~= 'table' then return nil, 'Invalid ped animation' end
        local dict = safeText(entry.anim.dict or entry.anim[1], 128, false)
        local clip = safeText(entry.anim.clip or entry.anim[2], 96, false)
        if not dict or not clip then return nil, 'Invalid ped animation' end
        local flag = finite(entry.anim.flag or entry.anim[3] or 1, 51)
        if not flag or flag < 0 or flag % 1 ~= 0 then return nil, 'Invalid ped animation flag' end
        anim = { dict = dict, clip = clip, flag = flag }
        scenario = nil
    end
    return { model = model, coords = { x = x, y = y, z = z, w = w % 360.0 }, scenario = scenario, anim = anim }
end

local function formatAnimationEntry(entry)
    local lines = {
        'TSSBridgeLabCreatedPedAnimations[#TSSBridgeLabCreatedPedAnimations + 1] = {',
        ('    model = %q,'):format(entry.model),
        ('    coords = vector4(%.3f, %.3f, %.3f, %.3f),')
            :format(entry.coords.x, entry.coords.y, entry.coords.z, entry.coords.w),
    }
    if entry.anim then
        lines[#lines + 1] = ('    anim = { dict = %q, clip = %q, flag = %d },')
            :format(entry.anim.dict, entry.anim.clip, entry.anim.flag)
    elseif entry.scenario then
        lines[#lines + 1] = ('    scenario = %q,'):format(entry.scenario)
        lines[#lines + 1] = '    useEnterAnim = false,'
    end
    lines[#lines + 1] = '}'
    lines[#lines + 1] = ''
    return table.concat(lines, '\n') .. '\n'
end

function Storage.Save(source, submitted)
    local now = GetGameTimer()
    if saveCooldowns[source] and now - saveCooldowns[source] < 1500 then
        return { success = false, error = 'Wait before saving again' }
    end
    if type(submitted) ~= 'table' or #submitted < 1 or #submitted > 100 then
        return { success = false, error = 'Commit between 1 and 100 animation placements before saving' }
    end

    local validated = {}
    for i = 1, #submitted do
        local ped, validationError = validate(submitted[i])
        if not ped then return { success = false, error = ('Placement %d: %s'):format(i, validationError) } end
        if not ped.anim and not ped.scenario then
            return { success = false, error = ('Placement %d has no animation or scenario'):format(i) }
        end
        validated[i] = ped
    end

    local current = LoadResourceFile(resourceName, animationOutputPath) or ''
    if #current > 2097152 then
        return { success = false, error = 'created_ped_animation.lua has reached its 2 MB safety limit' }
    end
    if current:match('^%s*$') then current = animationHeader end
    if current:sub(-1) ~= '\n' then current = current .. '\n' end
    local output = {}
    for i = 1, #validated do output[i] = formatAnimationEntry(validated[i]) end
    if SaveResourceFile(resourceName, animationOutputPath, current .. table.concat(output), -1) == false then
        return { success = false, error = 'Unable to write bridge_lab/exported_data/created_ped_animation.lua' }
    end

    saveCooldowns[source] = now
    return {
        success = true,
        message = ('Saved %d animation placement%s to bridge_lab/exported_data/created_ped_animation.lua')
            :format(#validated, #validated == 1 and '' or 's'),
    }
end

AddEventHandler('playerDropped', function() saveCooldowns[source] = nil end)
