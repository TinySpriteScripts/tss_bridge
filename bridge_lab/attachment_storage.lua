-- Validates and persists Bridge Lab-created prop attachment definitions.
TSSBridgeLabAttachmentStorage = {}

local Storage = TSSBridgeLabAttachmentStorage
local resourceName = GetCurrentResourceName()
local outputPath = 'bridge_lab/created_prop_attatchments.lua'
local saveCooldowns = {}
local header = [[-- Generated by the TSS Bridge Lab Prop Attachment Creator.
-- This file is append-only and is not loaded automatically by tss_bridge.
TSSBridgeLabCreatedPropAttatchments = TSSBridgeLabCreatedPropAttatchments or {}

]]

local function finite(value, limit)
    value = tonumber(value)
    if not value or value ~= value or math.abs(value) > (limit or 1000.0) then return nil end
    return value + 0.0
end

local function safeName(value, maximum)
    if type(value) ~= 'string' then return nil end
    value = value:match('^%s*(.-)%s*$')
    if value == '' or #value > (maximum or 64) or not value:match('^[%w _%-]+$') then return nil end
    return value
end

local function vector(value, limit)
    if type(value) ~= 'table' then return nil end
    local x, y, z = finite(value.x, limit), finite(value.y, limit), finite(value.z, limit)
    if not x or not y or not z then return nil end
    return { x = x, y = y, z = z }
end

local function animationText(value, maximum)
    if type(value) ~= 'string' then return nil end
    value = value:match('^%s*(.-)%s*$')
    if value == '' or #value > maximum or not value:match('^[%w_@%-%./]+$') then return nil end
    return value
end

local function validate(submitted)
    if type(submitted) ~= 'table' then return nil, 'Invalid attachment payload' end
    local name = safeName(submitted.name)
    local model = safeName(submitted.model, 80)
    local bone = type(submitted.bone) == 'table' and submitted.bone or nil
    local boneName = bone and safeName(bone.name, 48)
    local boneId = bone and finite(bone.id, 65535)
    local offset = vector(submitted.offset, 25.0)
    local rotation = vector(submitted.rotation, 360000.0)
    if not name then return nil, 'Invalid attachment name' end
    if not model then return nil, 'Invalid prop model' end
    if not boneName or not boneId then return nil, 'Invalid ped bone' end
    if not offset or not rotation then return nil, 'Invalid attachment transform' end
    rotation.x, rotation.y, rotation.z = rotation.x % 360.0, rotation.y % 360.0, rotation.z % 360.0

    local animation
    if submitted.animation ~= nil then
        if type(submitted.animation) ~= 'table' then return nil, 'Invalid attachment animation' end
        local dict = animationText(submitted.animation.dict, 128)
        local clip = animationText(submitted.animation.clip, 96)
        local flag = finite(submitted.animation.flag, 1024)
        if not dict or not clip or not flag or flag < 0 or flag % 1 ~= 0 then
            return nil, 'Invalid attachment animation'
        end
        animation = { dict = dict, clip = clip, flag = flag }
    end

    return {
        name = name, model = model, bone = { name = boneName, id = boneId },
        offset = offset, rotation = rotation, animation = animation,
    }
end

local function vec3(value)
    return ('vec3(%.4f, %.4f, %.4f)'):format(value.x, value.y, value.z)
end

local function formatAttachment(attachment)
    local lines = {
        'TSSBridgeLabCreatedPropAttatchments[#TSSBridgeLabCreatedPropAttatchments + 1] = {',
        ('    name = %q,'):format(attachment.name),
        ('    model = %q,'):format(attachment.model),
        ('    bone = { name = %q, id = %d },'):format(attachment.bone.name, attachment.bone.id),
        ('    offset = %s,'):format(vec3(attachment.offset)),
        ('    rotation = %s,'):format(vec3(attachment.rotation)),
    }
    if attachment.animation then
        lines[#lines + 1] = ('    animation = { dict = %q, clip = %q, flag = %d },')
            :format(attachment.animation.dict, attachment.animation.clip, attachment.animation.flag)
    end
    lines[#lines + 1] = '}'
    lines[#lines + 1] = ''
    return table.concat(lines, '\n') .. '\n'
end

function Storage.Save(source, submitted)
    local now = GetGameTimer()
    if saveCooldowns[source] and now - saveCooldowns[source] < 1500 then
        return { success = false, error = 'Wait before saving another attachment' }
    end
    local attachment, validationError = validate(submitted)
    if not attachment then return { success = false, error = validationError } end

    local current = LoadResourceFile(resourceName, outputPath) or ''
    if #current > 2097152 then return { success = false, error = 'created_prop_attatchments.lua has reached its 2 MB safety limit' } end
    if current:match('^%s*$') then current = header end
    if current:sub(-1) ~= '\n' then current = current .. '\n' end
    local saved = SaveResourceFile(resourceName, outputPath, current .. formatAttachment(attachment), -1)
    if saved == false then return { success = false, error = 'Unable to write bridge_lab/created_prop_attatchments.lua' } end
    saveCooldowns[source] = now
    return {
        success = true,
        message = ('Saved %s to bridge_lab/created_prop_attatchments.lua'):format(attachment.name),
        attachment = attachment,
    }
end

AddEventHandler('playerDropped', function()
    saveCooldowns[source] = nil
end)
