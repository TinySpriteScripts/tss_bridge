-- Validates and persists Bridge Lab-created zones. Client-provided Lua is never accepted.
TSSBridgeLabZoneStorage = {}

local Storage = TSSBridgeLabZoneStorage
local resourceName = GetCurrentResourceName()
local outputPath = 'bridge_lab/created_zones.lua'
local saveCooldowns = {}
local header = [[-- Generated by the TSS Bridge Lab PolyZone Creator.
-- This file is append-only and is not loaded automatically by tss_bridge.
TSSBridgeLabCreatedZones = TSSBridgeLabCreatedZones or {}

]]

local function finite(value, limit)
    value = tonumber(value)
    if not value or value ~= value or math.abs(value) > (limit or 10000.0) then return nil end
    return value + 0.0
end

local function coordinate(value)
    if type(value) ~= 'table' then return nil end
    local x = finite(value.x)
    local y = finite(value.y)
    local z = finite(value.z, 2000.0)
    if not x or not y or not z then return nil end
    return { x = x, y = y, z = z }
end

local function dimension(value)
    value = finite(value, 1000.0)
    if not value or value < 0.1 then return nil end
    return value
end

local function zoneName(value)
    if type(value) ~= 'string' then return nil end
    value = value:match('^%s*(.-)%s*$')
    if value == '' or #value > 64 or not value:match('^[%w _%-]+$') then return nil end
    return value
end

local function validateBox(zone, name)
    local center = coordinate(zone.coords)
    local width = dimension(zone.width)
    local length = dimension(zone.length)
    local height = dimension(zone.height)
    local heading = finite(zone.heading, 360000.0)
    if not center or not width or not length or not height or not heading then return nil, 'Invalid box dimensions' end

    heading = heading % 360.0
    return {
        type = 'box', name = name, coords = center,
        width = width, length = length, height = height, heading = heading,
        minZ = center.z - (height / 2.0), maxZ = center.z + (height / 2.0),
    }
end

local function validateCircle(zone, name)
    local center = coordinate(zone.coords)
    local radius = dimension(zone.radius)
    if not center or not radius then return nil, 'Invalid circle dimensions' end
    return { type = 'circle', name = name, coords = center, radius = radius, useZ = true }
end

local function validatePoly(zone, name)
    if type(zone.points) ~= 'table' or #zone.points < 3 or #zone.points > 128 then
        return nil, 'A polygon requires between 3 and 128 points'
    end

    local points, centerZ = {}, 0.0
    for i = 1, #zone.points do
        local point = coordinate(zone.points[i])
        if not point then return nil, ('Invalid polygon point %d'):format(i) end
        points[i] = point
        centerZ = centerZ + point.z
    end

    local area = 0.0
    for i = 1, #points do
        local nextPoint = points[i == #points and 1 or i + 1]
        area = area + (points[i].x * nextPoint.y) - (nextPoint.x * points[i].y)
    end
    if math.abs(area * 0.5) < 0.01 then return nil, 'Polygon points do not form a usable area' end

    centerZ = centerZ / #points
    local minZ = finite(zone.minZ, 2000.0) or (centerZ - 1.0)
    local maxZ = finite(zone.maxZ, 2000.0) or (centerZ + 2.0)
    if maxZ < minZ then return nil, 'Polygon maxZ cannot be below ground level' end

    return { type = 'poly', name = name, points = points, minZ = minZ, maxZ = maxZ }
end

local validators = { box = validateBox, circle = validateCircle, poly = validatePoly }

local function formatVec3(value)
    return ('vec3(%.3f, %.3f, %.3f)'):format(value.x, value.y, value.z)
end

local function formatZone(zone)
    local lines = {
        'TSSBridgeLabCreatedZones[#TSSBridgeLabCreatedZones + 1] = {',
        ('    type = %q,'):format(zone.type),
        ('    name = %q,'):format(zone.name),
    }

    if zone.type == 'box' then
        lines[#lines + 1] = ('    coords = %s,'):format(formatVec3(zone.coords))
        lines[#lines + 1] = ('    size = vec3(%.3f, %.3f, %.3f),'):format(zone.width, zone.length, zone.height)
        lines[#lines + 1] = ('    width = %.3f,'):format(zone.width)
        lines[#lines + 1] = ('    length = %.3f,'):format(zone.length)
        lines[#lines + 1] = ('    heading = %.3f,'):format(zone.heading)
        lines[#lines + 1] = ('    minZ = %.3f,'):format(zone.minZ)
        lines[#lines + 1] = ('    maxZ = %.3f,'):format(zone.maxZ)
    elseif zone.type == 'circle' then
        lines[#lines + 1] = ('    coords = %s,'):format(formatVec3(zone.coords))
        lines[#lines + 1] = ('    radius = %.3f,'):format(zone.radius)
        lines[#lines + 1] = '    useZ = true,'
    else
        lines[#lines + 1] = '    points = {'
        for i = 1, #zone.points do
            local point = zone.points[i]
            lines[#lines + 1] = ('        vec2(%.3f, %.3f), -- ground Z %.3f'):format(point.x, point.y, point.z)
        end
        lines[#lines + 1] = '    },'
        lines[#lines + 1] = ('    minZ = %.3f,'):format(zone.minZ)
        lines[#lines + 1] = ('    maxZ = %.3f,'):format(zone.maxZ)
    end

    lines[#lines + 1] = '}'
    lines[#lines + 1] = ''
    return table.concat(lines, '\n') .. '\n'
end

--- Validates and appends a created zone to bridge_lab/created_zones.lua.
---@param source integer
---@param submitted table
---@return table result
function Storage.Save(source, submitted)
    local now = GetGameTimer()
    if saveCooldowns[source] and now - saveCooldowns[source] < 1500 then
        return { success = false, error = 'Wait before saving another zone' }
    end

    if type(submitted) ~= 'table' then return { success = false, error = 'Invalid zone payload' } end
    local zoneType = type(submitted.type) == 'string' and submitted.type:lower() or ''
    local validator = validators[zoneType]
    local name = zoneName(submitted.name)
    if not validator or not name then return { success = false, error = 'Invalid zone type or name' } end

    local zone, validationError = validator(submitted, name)
    if not zone then return { success = false, error = validationError } end

    local current = LoadResourceFile(resourceName, outputPath) or ''
    if #current > 2097152 then return { success = false, error = 'created_zones.lua has reached its 2 MB safety limit' } end
    if current:match('^%s*$') then current = header end
    if current:sub(-1) ~= '\n' then current = current .. '\n' end

    local saved = SaveResourceFile(resourceName, outputPath, current .. formatZone(zone), -1)
    if saved == false then return { success = false, error = 'Unable to write bridge_lab/created_zones.lua' } end

    saveCooldowns[source] = now
    return { success = true, message = ('Saved %s to bridge_lab/created_zones.lua'):format(name), zone = zone }
end

AddEventHandler('playerDropped', function()
    saveCooldowns[source] = nil
end)
