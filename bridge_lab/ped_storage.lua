-- Validates and persists definitions created by the Bridge Lab Ped Spawner.
TSSBridgeLabPedStorage = {}

local Storage = TSSBridgeLabPedStorage
local resourceName = GetCurrentResourceName()
local outputPath = 'bridge_lab/created_peds.lua'
local saveCooldowns = {}
local header = [[-- Generated by the TSS Bridge Lab Ped Spawner.
-- This file is append-only and is not loaded automatically by tss_bridge.
TSSBridgeLabCreatedPeds = TSSBridgeLabCreatedPeds or {}

]]

local function finite(value, limit)
    value = tonumber(value)
    if not value or value ~= value or math.abs(value) > (limit or 10000.0) then return nil end
    return value + 0.0
end

local function safeText(value, maximum, optional)
    if value == nil and optional then return nil end
    if type(value) ~= 'string' then return nil end
    value = value:match('^%s*(.-)%s*$')
    if value == '' then return optional and nil or nil end
    if #value > maximum or value:find('[%c]') or not value:match('^[%w_@%-%./]+$') then return nil end
    return value
end

local function validate(entry)
    if type(entry) ~= 'table' or type(entry.coords) ~= 'table' then return nil, 'Invalid ped payload' end
    local model = safeText(entry.model, 80, false)
    local x, y = finite(entry.coords.x), finite(entry.coords.y)
    local z, w = finite(entry.coords.z, 2000.0), finite(entry.coords.w, 360000.0)
    if not model or not x or not y or not z or not w then return nil, 'Invalid ped model or coordinates' end
    local scenario = safeText(entry.scenario, 96, true)
    local anim
    if entry.anim ~= nil then
        if type(entry.anim) ~= 'table' then return nil, 'Invalid ped animation' end
        local dict = safeText(entry.anim.dict or entry.anim[1], 128, false)
        local clip = safeText(entry.anim.clip or entry.anim[2], 96, false)
        if not dict or not clip then return nil, 'Invalid ped animation' end
        anim = { dict, clip }
        scenario = nil
    end
    return { model = model, coords = { x = x, y = y, z = z, w = w % 360.0 }, scenario = scenario, anim = anim }
end

local function formatEntry(entry)
    local lines = {
        'TSSBridgeLabCreatedPeds[#TSSBridgeLabCreatedPeds + 1] = {',
        ('    model = %q,'):format(entry.model),
        ('    coords = vector4(%.3f, %.3f, %.3f, %.3f),'):format(entry.coords.x, entry.coords.y, entry.coords.z, entry.coords.w),
        entry.scenario and ('    scenario = %q,'):format(entry.scenario) or '    scenario = nil,',
    }
    if entry.anim then
        lines[#lines + 1] = '    anim = {'
        lines[#lines + 1] = ('        %q,'):format(entry.anim[1])
        lines[#lines + 1] = ('        %q,'):format(entry.anim[2])
        lines[#lines + 1] = '    },'
    else
        lines[#lines + 1] = '    anim = nil,'
    end
    lines[#lines + 1] = '}'
    lines[#lines + 1] = ''
    return table.concat(lines, '\n') .. '\n'
end

function Storage.Save(source, submitted)
    local now = GetGameTimer()
    if saveCooldowns[source] and now - saveCooldowns[source] < 1500 then return { success = false, error = 'Wait before saving again' } end
    if type(submitted) ~= 'table' or #submitted < 1 or #submitted > 100 then return { success = false, error = 'Submit between 1 and 100 peds' } end
    local validated = {}
    for i = 1, #submitted do
        local ped, validationError = validate(submitted[i])
        if not ped then return { success = false, error = ('Ped %d: %s'):format(i, validationError) } end
        validated[i] = ped
    end
    local current = LoadResourceFile(resourceName, outputPath) or ''
    if #current > 2097152 then return { success = false, error = 'created_peds.lua has reached its 2 MB safety limit' } end
    if current:match('^%s*$') then current = header end
    if current:sub(-1) ~= '\n' then current = current .. '\n' end
    local output = {}
    for i = 1, #validated do output[i] = formatEntry(validated[i]) end
    if SaveResourceFile(resourceName, outputPath, current .. table.concat(output), -1) == false then
        return { success = false, error = 'Unable to write bridge_lab/created_peds.lua' }
    end
    saveCooldowns[source] = now
    return { success = true, message = ('Saved %d ped%s to bridge_lab/created_peds.lua'):format(#validated, #validated == 1 and '' or 's') }
end

AddEventHandler('playerDropped', function() saveCooldowns[source] = nil end)
