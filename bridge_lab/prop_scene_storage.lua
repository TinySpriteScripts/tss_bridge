-- Validates and persists prop scenes created by the Bridge Lab.
TSSBridgeLabPropSceneStorage = {}

local Storage = TSSBridgeLabPropSceneStorage
local resourceName = GetCurrentResourceName()
local outputPath = 'bridge_lab/exported_data/created_prop_scenes.lua'
local saveCooldowns = {}
local header = [[-- Generated by the TSS Bridge Lab Prop Scene Editor.
-- Scaling uses SetEntityMatrix and is visual; GTA collision bounds are not resized.
-- This file is append-only and is not loaded automatically by tss_bridge.
TSSBridgeLabCreatedPropScenes = TSSBridgeLabCreatedPropScenes or {}

]]

local function finite(value, limit)
    value = tonumber(value)
    if not value or value ~= value or math.abs(value) > (limit or 10000.0) then return nil end
    return value + 0.0
end

local function safeName(value, maximum, pattern)
    if type(value) ~= 'string' then return nil end
    value = value:match('^%s*(.-)%s*$')
    if value == '' or #value > maximum or value:find('[%c]') then return nil end
    if pattern and not value:match(pattern) then return nil end
    return value
end

local function vector(value, limit, minimum, maximum)
    if type(value) ~= 'table' then return nil end
    local x, y, z = finite(value.x, limit), finite(value.y, limit), finite(value.z, limit)
    if not x or not y or not z then return nil end
    if minimum and (x < minimum or y < minimum or z < minimum) then return nil end
    if maximum and (x > maximum or y > maximum or z > maximum) then return nil end
    return { x = x, y = y, z = z }
end

local function validate(submitted)
    if type(submitted) ~= 'table' then return nil, 'Invalid scene payload' end
    local name = safeName(submitted.name, 64, '^[%w_%-]+$')
    if not name then return nil, 'Invalid scene name' end
    if type(submitted.props) ~= 'table' or #submitted.props < 1 or #submitted.props > 200 then
        return nil, 'A scene must contain between 1 and 200 props'
    end
    local props = {}
    for i = 1, #submitted.props do
        local prop = submitted.props[i]
        if type(prop) ~= 'table' then return nil, ('Prop %d is invalid'):format(i) end
        local model = safeName(prop.model, 80, '^[%w_%-]+$')
        local coords = vector(prop.coords, 10000.0)
        local rotation = vector(prop.rotation, 360000.0)
        local scale = vector(prop.scale, 10.0, 0.05, 10.0)
        if not model or not coords or not rotation or not scale then
            return nil, ('Prop %d has an invalid model or transform'):format(i)
        end
        rotation.x, rotation.y, rotation.z = rotation.x % 360.0, rotation.y % 360.0, rotation.z % 360.0
        props[i] = { model = model, coords = coords, rotation = rotation, scale = scale }
    end
    return { name = name, props = props }
end

local function formatScene(scene)
    local rows = { ('TSSBridgeLabCreatedPropScenes[%q] = {'):format(scene.name) }
    for _, prop in ipairs(scene.props) do
        rows[#rows + 1] = ('    { model = %q, coords = vector3(%.3f, %.3f, %.3f),'):format(
            prop.model, prop.coords.x, prop.coords.y, prop.coords.z)
        rows[#rows + 1] = ('      rotation = vector3(%.3f, %.3f, %.3f), scale = vector3(%.3f, %.3f, %.3f) },'):format(
            prop.rotation.x, prop.rotation.y, prop.rotation.z,
            prop.scale.x, prop.scale.y, prop.scale.z)
    end
    rows[#rows + 1] = '}'
    rows[#rows + 1] = ''
    return table.concat(rows, '\n') .. '\n'
end

function Storage.Save(source, submitted)
    local now = GetGameTimer()
    if saveCooldowns[source] and now - saveCooldowns[source] < 1500 then
        return { success = false, error = 'Wait before saving another prop scene' }
    end
    local scene, validationError = validate(submitted)
    if not scene then return { success = false, error = validationError } end
    local current = LoadResourceFile(resourceName, outputPath) or ''
    if #current > 2097152 then
        return { success = false, error = 'created_prop_scenes.lua has reached its 2 MB safety limit' }
    end
    if current:match('^%s*$') then current = header end
    if current:sub(-1) ~= '\n' then current = current .. '\n' end
    if SaveResourceFile(resourceName, outputPath, current .. formatScene(scene), -1) == false then
        return { success = false, error = 'Unable to write bridge_lab/exported_data/created_prop_scenes.lua' }
    end
    saveCooldowns[source] = now
    return {
        success = true,
        message = ('Saved prop scene %s with %d prop%s to bridge_lab/exported_data/created_prop_scenes.lua')
            :format(scene.name, #scene.props, #scene.props == 1 and '' or 's'),
    }
end

AddEventHandler('playerDropped', function() saveCooldowns[source] = nil end)
