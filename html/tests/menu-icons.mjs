import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const require = createRequire(import.meta.url);
const { outputFiles } = await build({entryPoints:['src/MenuIcon.jsx'],bundle:true,write:false,platform:'node',format:'cjs',external:['react','lucide-react']});
const module = { exports: {} };
new Function('require','module','exports', outputFiles[0].text)(require,module,module.exports);
const Icon = module.exports.default;
const render = (icon) => renderToStaticMarkup(React.createElement(Icon,{icon,size:30}));
assert.match(render({type:'image',src:'https://cfx-nui-tss-blipcreator/images/blips/40.png'}), /<img[^>]+width="30"/);
assert.match(render('https://example.com/image.png'), /<img/);
assert.match(render('fas fa-house'), /bridge-font-icon fas fa-house/);
assert.match(render('fa-solid fa-house'), /bridge-font-icon fa-solid fa-house/);
assert.match(render('fa-brands fa-discord'), /bridge-font-icon fa-brands fa-discord/);
assert.match(render('wrench'), /lucide-wrench/);
assert.match(render(undefined), /lucide-circle-dot/);
assert.match(render({type:'image',src:42}), /lucide-image-off/);
assert.match(render({type:'image',src:'https://example.com/" onload="bad'}), /&quot;/);
console.log('PASS: image URLs, resource images, Font Awesome variants, named icons and fallback rendering');
